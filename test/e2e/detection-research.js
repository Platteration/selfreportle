/* Real detector/report UI component checks in an ordinary browser page.
 * Only extension messaging/storage is simulated; no extension policy changes.
 * Standalone: node test/e2e/detection-research.js
 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '../..');

async function run(context) {
  let page = await context.newPage();
  const errors = [];
  try {
    page.on('pageerror', (e) => errors.push(e.message));
    await page.setContent('<html lang="en"><head><title>Research detection fixture</title></head><body><main><p id="vocabulary"></p><p id="format"></p><p id="gemma"></p><p id="mixed"></p><p id="human">This tapestry was woven by hand for the museum. Visitors can see the repairs along the edge. A volunteer wrote this description.</p></main></body></html>');
    await page.evaluate(() => {
      document.getElementById('vocabulary').textContent = 'The study delves into intricate results, showcasing noteworthy details that bolster nuanced interpretations. '
        + 'The team reviewed the records and described the observations using their usual methods. '.repeat(8);
      document.getElementById('format').textContent = '<|start_header_id|>assistant<|end_header_id|>\nA sample answer.<|eot_id|>';
      document.getElementById('gemma').textContent = 'This paragraph was generated by Google Gemma 3.';
      document.getElementById('mixed').textContent = 'This section was generated by Claude and edited by Qwen3.';
      globalThis.chrome = { storage: {
        sync: { get(defaults, done) { done({ ...defaults, showPill: false, showImageBadges: false, fetchImages: false, rememberDomains: false }); } },
        onChanged: { addListener() {} },
      }, runtime: {
        onMessage: { addListener() {} },
        async sendMessage(message) {
          if (message.type === 'srl:page-result') globalThis.componentReport = message.result;
          return {};
        },
      } };
    });
    await page.addStyleTag({ path: path.join(ROOT, 'content/content.css') });
    const scripts = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8')).content_scripts[0].js;
    // evaluate the real scripts without putting their source in the document:
    // actual content scripts likewise do not become page <script> nodes.
    for (const script of scripts) await page.evaluate(fs.readFileSync(path.join(ROOT, script), 'utf8'));
    await page.waitForFunction(() => globalThis.componentReport && componentReport.text.flagged.length >= 4);
    const report = await page.evaluate(() => JSON.parse(JSON.stringify(componentReport)));
    const research = report.text.flagged.flatMap((b) => b.signals).find((s) => s.id === 'research-vocabulary');
    assert.deepEqual(research.sourceIds, ['excess-vocabulary'], 'source survives block serialization');
    assert.equal(research.patternIds.length, 6, 'distinct research word groups survive');
    const artifact = report.text.flagged.flatMap((b) => b.signals).find((s) => s.id === 'model-artifact' && s.toolId === 'meta');
    assert.match(artifact.sourceUrls[0], /meta-llama/);
    assert.deepEqual(artifact.patternIds, ['llama-header']);
    const mixed = report.text.flagged.find((b) => b.excerpt.includes('generated by Claude'));
    assert.deepEqual(mixed.attributions.map((a) => a.id), ['anthropic', 'alibaba'], 'both credited models preserved within one block');
    for (const id of ['meta', 'gemma', 'anthropic', 'alibaba']) {
      const system = report.aiSystems.find((s) => s.id === id);
      assert.ok(system && system.layers.includes('text'), id + ' appears in Tools');
    }
    assert.equal(report.aiSystems.find((s) => s.id === 'meta').confidence, 'inferred', 'format compatibility remains inferred');
    assert.equal(await page.locator('#human').getAttribute('data-srl-text'), null, 'ordinary museum description not marked');
    assert.deepEqual(errors, [], 'detector has no browser errors');
    await page.close();

    page = await context.newPage();
    page.on('pageerror', (e) => errors.push(e.message));
    const html = fs.readFileSync(path.join(ROOT, 'popup/popup.html'), 'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '').replace(/<link\b[^>]*>/g, '');
    await page.setContent(html);
    await page.addStyleTag({ path: path.join(ROOT, 'popup/popup.css') });
    await page.evaluate((data) => {
      const tab = { id: 1, url: 'https://research.example/demo' };
      globalThis.chrome = { tabs: { async query() { return [tab]; }, async get() { return tab; } },
        runtime: { openOptionsPage() {}, async sendMessage(message) { return message.type === 'srl:get-result' ? data : {}; } },
        storage: {
          sync: { get(defaults, done) { done(defaults); } },
          session: { async get() { return { 'tab:1': data }; } },
          onChanged: { addListener() {} },
        },
      };
    }, report);
    const popupScripts = [...fs.readFileSync(path.join(ROOT, 'popup/popup.html'), 'utf8').matchAll(/src="([^"]+\.js)"/g)].map((m) => path.resolve(ROOT, 'popup', m[1]));
    for (const script of popupScripts) await page.evaluate(fs.readFileSync(script, 'utf8'));
    await page.waitForFunction(() => !!document.getElementById('panel-text'));
    await page.locator('#tab-text').click();
    const panel = page.locator('#panel-text');
    assert.ok(await panel.getByText('Research catalogue reviewed', { exact: false }).count());
    for (const url of ['https://github.com/berenslab/llm-excess-vocab', artifact.sourceUrls[0]]) {
      const link = panel.locator('a').filter({ hasText: url.includes('berenslab') ? 'excess vocabulary' : 'Llama-family' }).first();
      assert.equal(await link.getAttribute('href'), url);
      assert.equal(await link.getAttribute('rel'), 'noopener noreferrer');
    }
    for (const theme of ['light', 'dark']) {
      await page.emulateMedia({ colorScheme: theme });
      const colors = await panel.locator('.sig .note a').evaluateAll((links) => links.map((link) => [getComputedStyle(link).color, getComputedStyle(document.body).backgroundColor]));
      assert.ok(colors.length >= 2, 'research and format links rendered');
      for (const [foreground, background] of colors) assert.ok(contrast(foreground, background) >= 4.5, theme + ' source link meets AA');
      if (process.env.SRL_SCREENSHOT_DIR) {
        fs.mkdirSync(process.env.SRL_SCREENSHOT_DIR, { recursive: true });
        await page.screenshot({ path: path.join(process.env.SRL_SCREENSHOT_DIR, 'research-' + theme + '.png') });
      }
    }
    await page.locator('#tab-tools').click();
    for (const name of ['Meta AI', 'Google Gemma', 'Anthropic', 'Alibaba Qwen']) {
      assert.ok(await page.locator('#panel-tools').getByText(name, { exact: false }).count(), name + ' rendered in Tools');
    }
    assert.deepEqual(errors, [], 'popup has no browser errors');
    console.log('Research detection browser checks OK: real analyser, sourced block reports, multiple models, popup citations and Tools.');
  } finally { if (!page.isClosed()) await page.close(); }
}

function contrast(a, b) {
  const luminance = (rgb) => {
    const channels = rgb.match(/[\d.]+/g).slice(0, 3).map(Number).map((v) => {
      v /= 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4;
    });
    return channels[0] * .2126 + channels[1] * .7152 + channels[2] * .0722;
  };
  const x = luminance(a), y = luminance(b);
  return (Math.max(x, y) + .05) / (Math.min(x, y) + .05);
}

module.exports = { run };
if (require.main === module) {
  (async () => {
    let playwright;
    try { playwright = require('playwright'); } catch {
      playwright = require(path.join(require('node:child_process').execSync('npm root -g').toString().trim(), 'playwright'));
    }
    const browser = await playwright.chromium.launch({ headless: false, executablePath: process.env.PW_CHROMIUM || undefined, args: ['--headless=new'] });
    try { await run(await browser.newContext({ viewport: { width: 440, height: 620 } })); }
    finally { await browser.close(); }
  })().catch((e) => { console.error(e); process.exitCode = 1; });
}
