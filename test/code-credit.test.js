const test = require('node:test');
const assert = require('node:assert/strict');
const A = require('../lib/site-analyzer.js');

test('negated code-generation comments and inline credits do not signal AI use', () => {
  for (const key of ['comments', 'inlineScripts']) {
    for (const credit of ['not generated by Qwen3', 'never written by IBM Granite 3.1', 'not AI-generated']) {
      const result = A.analyzeSite({ [key]: ['// This code was ' + credit + '.'], bodyText: '' });
      assert.equal(result.verdict, 'no-signal', key + ': ' + credit);
      assert.equal(result.signals.some((s) => s.id === 'code-comment'), false);
    }
  }
});

test('a later positive code credit survives an earlier negated credit', () => {
  for (const key of ['comments', 'inlineScripts']) {
    const source = '// Not generated by Qwen3.\n// ' + 'Ordinary human comment. '.repeat(10)
      + '\n// This helper was written by IBM Granite 3.1.';
    const result = A.analyzeSite({ [key]: [source], bodyText: '' });
    assert.equal(result.verdict, 'ai-assisted', key);
    const evidence = result.signals.find((s) => s.id === 'code-comment');
    assert.ok(evidence);
    assert.match(evidence.detail, /written by IBM Granite 3\.1/);
  }
});

test('code credits preserve human-name negatives and same-line product positives', () => {
  for (const key of ['comments', 'inlineScripts']) {
    assert.equal(A.analyzeSite({ [key]: ['// Written by Claude Monet.'] }).verdict, 'no-signal');
    for (const credit of ['Written by Claude Code.', 'Generated by CodeGemma.', 'Generated by Claude\n// Published today.']) {
      assert.equal(A.analyzeSite({ [key]: ['// ' + credit] }).verdict, 'ai-assisted', credit);
    }
  }
});
