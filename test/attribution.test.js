test('mixed declarations in one block retain their order and every credited system', () => {
  const text = 'This section was generated by Claude and edited by Qwen.';
  const disclosures = require('../lib/signals.js').findDisclosures(text);
  assert.deepEqual(disclosures.map((d) => d.match), ['generated by Claude', 'edited by Qwen']);
  const result = { verdict: 'ai-disclosed', disclosures };
  assert.equal(A.attributeText(result).id, 'anthropic');
  const systems = A.attributeTextSystems(result);
  assert.deepEqual(systems.map((s) => s.id), ['anthropic', 'alibaba']);
  assert.ok(systems.every((s) => s.confidence === 'declared'));
  assert.deepEqual(A.attributeTextSystems({ verdict: 'possible-ai', disclosures: [
    { match: 'generated by Claude', context: text, level: 'generated' },
    { match: 'generated by Claude', level: 'generated' },
    { match: 'not generated by Qwen', level: 'human' },
  ], page: { signals: [
    { id: 'model-artifact', toolId: 'gemma', detail: 'Gemma conversation format' },
    { id: 'model-artifact', toolId: 'gemma', detail: 'Repeated Gemma conversation format' },
    { id: 'model-artifact', toolId: null, detail: 'Shared reasoning delimiters' },
  ] } }).map((s) => [s.id, s.confidence]), [['anthropic', 'declared'], ['gemma', 'inferred']]);
  assert.deepEqual(A.attributeTextSystems({ verdict: 'likely-ai', page: { signals: [
    { id: 'lexicon', detail: 'delve and tapestry' },
  ] } }), []);
});

