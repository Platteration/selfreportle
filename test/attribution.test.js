test('new catalog identifiers and format rules retain primary source references', () => {
  for (const model of M.MODELS) {
    assert.match(model.source, /^https:\/\/github\.com\//, model.id);
    assert.ok(model.year >= 2021 && model.year <= 2025, model.id);
    assert.ok(model.match instanceof RegExp, model.id);
    assert.ok(model.disclosureName && model.kinds.length, model.id);
  }
  for (const artifact of M.TEXT_ARTIFACTS) {
    assert.match(artifact.source, /^https:\/\/github\.com\//, artifact.id);
    assert.ok(artifact.markers.length >= 2, artifact.id);
    assert.ok(artifact.markers.every((r) => r instanceof RegExp), artifact.id);
    if (artifact.toolId) assert.ok(A.profile(artifact.toolId), artifact.id);
  }
});

