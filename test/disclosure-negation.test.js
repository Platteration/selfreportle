const test = require('node:test');
const assert = require('node:assert/strict');
const S = require('../lib/signals.js');

const cases = [
  { lang: 'en', negation: 'not ', generated: 'This text was not generated by Google Gemma 3.', assisted: 'This text was not edited by Qwen3.', auxiliary: 'This text has not been generated by Google Gemma 3.' },
  { lang: 'de', negation: 'nicht ', generated: 'Dieser Text wurde nicht erstellt mit Qwen3.', assisted: 'Dieser Text wurde nicht mit Hilfe von Qwen3 erstellt.', auxiliary: 'Dieser Text wurde nicht vollständig erstellt mit Qwen3.' },
  { lang: 'fr', negation: 'non ', generated: 'Texte non généré par Google Gemma 3.', assisted: 'Texte non édité par Google Gemma 3.', auxiliary: "Texte n'a pas été généré par Google Gemma 3." },
  { lang: 'es', negation: 'no ', generated: 'Texto no generado con IBM Granite 3.1.', assisted: 'Texto no editado con IBM Granite 3.1.', auxiliary: 'Texto no fue generado con IBM Granite 3.1.' },
  { lang: 'nl', negation: 'niet ', generated: 'Tekst niet gemaakt met Cohere Command R.', assisted: 'Tekst niet met hulp van Cohere Command R geschreven.', auxiliary: 'Tekst is niet volledig gemaakt met Cohere Command R.' },
  { lang: 'it', negation: 'non ', generated: 'Testo non generato con GLM-4.', assisted: 'Testo non modificato con GLM-4.', auxiliary: 'Testo non è stato generato con GLM-4.' },
  { lang: 'pt', negation: 'não ', generated: 'Texto não gerado por Kimi-K2.', assisted: 'Texto não editado por Kimi-K2.', auxiliary: 'Texto não foi gerado por Kimi-K2.' },
  { lang: 'pl', negation: 'nie ', generated: 'Tekst nie wygenerowany przez Microsoft Phi-4.', assisted: 'Tekst nie edytowany przez Microsoft Phi-4.', auxiliary: 'Tekst nie został wygenerowany przez Microsoft Phi-4.' },
];

function aiDisclosures(text, lang) {
  return S.findDisclosures(text, { lang }).filter((d) => d.level !== 'human');
}

test('accented French disclosure verbs have Unicode word boundaries', () => {
  for (const [text, level] of [
    ['Texte écrit par Google Gemma 3.', 'generated'],
    ['Texte édité par Google Gemma 3.', 'assisted'],
    ['Texte écrit par des humains.', 'human'],
    ['Textes écrits par des humains.', 'human'],
  ]) {
    const hits = S.findDisclosures(text, { lang: 'fr' });
    assert.equal(hits.length, 1, text);
    assert.equal(hits[0].level, level, text);
  }
  for (const text of ['Texte préécrit par Google Gemma 3.', 'Texte préédité par Google Gemma 3.', 'Texte non écrit par Google Gemma 3.']) {
    assert.deepEqual(aiDisclosures(text, 'fr'), [], text);
  }
});

for (const item of cases) {
  test(item.lang + ': direct negation suppresses generation and assistance while positive controls survive', () => {
    assert.deepEqual(aiDisclosures(item.generated, item.lang), []);
    assert.deepEqual(aiDisclosures(item.assisted, item.lang), []);
    assert.deepEqual(aiDisclosures(item.auxiliary, item.lang), []);
    for (const level of ['generated', 'assisted']) {
      const positive = item[level].replace(item.negation, '');
      const hits = aiDisclosures(positive, item.lang);
      assert.equal(hits.length, 1, positive);
      assert.equal(hits[0].level, level, positive);
      const combined = item[level] + ' ' + positive;
      const mixed = aiDisclosures(combined, item.lang);
      assert.equal(mixed.length, 1, combined);
      assert.ok(mixed[0].index > item[level].length, combined);
      assert.equal(mixed[0].level, level, combined);
    }
  });
}

test('a negated clause does not suppress a later positive clause in the same sentence', () => {
  const text = 'This text was not generated by Google Gemma 3, but generated by Qwen3.';
  const hits = aiDisclosures(text, 'en');
  assert.equal(hits.length, 1);
  assert.equal(hits[0].match, 'generated by Qwen3');
  assert.ok(hits[0].index > text.indexOf('but'));
  assert.equal(aiDisclosures('Not only generated by Qwen3, also edited by Claude.', 'en').length, 2);
  const separateLine = aiDisclosures('This heading ends with not\nGenerated by Qwen3.', 'en');
  assert.equal(separateLine.length, 1);
  assert.equal(separateLine[0].match, 'Generated by Qwen3');
});

test('English contracted negation accepts straight and curly quotes without matching ordinary words', () => {
  for (const text of ["This text wasn't generated by Qwen3.", "This text isn't edited by Google Gemma3.", 'This text wasn’t generated by Qwen3.', 'This text isn’t edited by Google Gemma3.']) {
    assert.deepEqual(aiDisclosures(text, 'en'), [], text);
  }
  for (const text of ['Now generated by Qwen3.', 'Noah generated by Qwen3.']) {
    assert.equal(aiDisclosures(text, 'en').length, 1, text);
  }
  const credit = /generated by Qwen3/.exec('This code wasn’t generated by Qwen3.');
  assert.equal(S.isNegatedOrPerson('This code wasn’t generated by Qwen3.', credit), true);
});

test('a line break after a product name begins a new sentence rather than a human surname', () => {
  for (const text of ['Generated by Claude\nPublished on October 12.', 'Written by Claude\nThis article discusses local parks.', 'Generated by Sora\nVideo credits follow below.', 'Generated by Claude\r\nPublished on October 12.']) {
    const hits = aiDisclosures(text, 'en');
    assert.equal(hits.length, 1, text);
    assert.equal(hits[0].level, 'generated', text);
  }
  for (const text of ['Written by Claude Monet.', 'Generated by Sora Tanaka.', 'Written by Claude\tMonet.']) {
    assert.deepEqual(aiDisclosures(text, 'en'), [], text);
  }
});
